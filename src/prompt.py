from __future__ import annotations

import json
from typing import Dict, Any, List


def build_tag_schema_prompt(review_texts: List[str]) -> str:
    """
    构建“标签体系生成”提示词。
    输入：
    - review_texts: 多条评论文本（用于让模型归纳标签）
    输出：
    - prompt: str
    """
    joined = "\n".join(t for t in review_texts if t)
    return f"""
## 您的任务：
你是一个电商产品分析专家。您的任务是基于我提供的一批用户购后评论文本，为该产品构建一个结构化的、多层级的分析标签体系。这个标签体系将用于后续对每条评论进行细致的分类和打标，以便深入洞察用户需求和反馈。

## 核心理论知识（请先学习并理解）

1. 用户价值层级模型： 我们将从用户的角度出发，将他们对产品的关注点和评价归纳到以下四个核心价值层级。您的标签设计需要围绕这些层级展开：
- 人群与场景: 描述的是“谁”在“什么情况下”使用或提及产品。这包括用户的身份特征、所处环境、使用产品的具体情境或期望达成的目标。
- 功能价值 : 指产品为了解决用户的核心问题所提供的具体功能、性能表现以及操作特性。
- 保障价值 : 涉及产品的质量、耐用性、安全性、可靠性，以及品牌提供的售前、售中、售后服务和支持。
- 体验价值 : 涵盖用户在与产品交互的整个生命周期中的主观感受，包括感官体验（外观、声音、气味等）、操作便捷性、情感连接等。

2. 标签设计原则：
- 层级性： 标签体系应具有清晰的层级结构（一级标签、二级标签、三级标签）。
- 覆盖性： 能够尽可能全面地覆盖评论中用户提及的主要议题。
- 互斥性（理想状态）： 同一级下的标签应尽可能互斥，避免语义重叠过多。
- 简洁性： 每个标签的名称应简洁明了，尽量不超过5个汉字。
- 客观性： 标签本身不应包含情感倾向（如“效果好”、“质量差”），仅客观描述讨论的主题（如“清洁效果”、“产品材质”）。情感分析将在后续打标步骤中独立进行。
- 可扩展性： 体系应具备一定的灵活性，方便未来根据新的评论内容进行补充和调整。

## 要求：
- 遵循 MECE 原则
- 三级标签：一级为“四个维度”(人群与场景\功能价值\保障价值\体验价值)，二级为“主题”，三级为“可观测的具体点”
- 输出格式要求：请以结构化的 JSON 输出您设计的标签体系，不要输出任何解释文字

### 输出 JSON 结构要求：
{{
  "人群与场景": {{
    "二级标签1": ["三级标签1", "三级标签2"],
    "二级标签2": ["三级标签1"]
  }},
  "功能价值": {{
    "二级标签1": ["三级标签1", "三级标签2"]
  }},
  "保障价值": {{
    "二级标签1": ["三级标签1"]
  }},
  "体验价值": {{
    "二级标签1": ["三级标签1"]
  }}
}}
### 输出示例（针对一款“猫咪自助理毛器”产品，仅作参考，您需要根据提供的实际评论生成））：
{{
  "人群与场景": {{
	  "人群特征": ["多猫家庭", "敏感肌人群"],
	  "使用场景/期望": ["减少浮毛", "出差携带"]
	}},
  "功能价值": {{
	"核心功能": ["理毛效果", "吸力强弱"],
	"易用性": ["操作便捷", "清洁方便"]
  }},
  "保障价值": {{
    "质量可靠": ["耐用性", "做工材质"],
    "售后服务": ["退换货体验", "客服响应"]
  }},
  "体验价值": {{
    "使用感受": ["噪音大小", "舒适度"],
    "外观设计": ["颜值", "体积重量"]
  }}
}}
## 用户评论示例：
{joined}
""".strip()


def build_review_tagging_prompt(tag_schema: Dict[str, Any], review_text: str) -> str:
    """
    构建“单条评论打标”提示词。

    输入：
    - tag_schema: 三级标签体系（JSON）
    - review_text: 单条评论正文

    输出：
    - prompt: str
    """
    tag_schema_str = json.dumps(tag_schema, ensure_ascii=False)
    review_text = (review_text or "").strip()
    return f"""
你是一个专业的评论标注员。

请根据以下标签体系，分析用户评论，并为其提取“多个二级主题下的多个三级标签”（如果存在）。

标签体系（JSON）：
{tag_schema_str}

用户评论：
{review_text}

输出要求：
- 只输出 JSON 对象，不要解释文字
- JSON 结构为：{{"一级标签": {{"二级标签": ["三级标签1", "三级标签2"]}}}}
- 仅允许一级标签为：人群与场景 / 功能价值 / 保障价值 / 体验价值
- 不要输出标签体系中不存在的二级或三级标签
- 没有命中的二级标签可以省略；如果整条评论没有任何命中，输出 {{}}
""".strip()


def build_report_writer_prompt(asin: str, analysis_markdown: str, product_title: str = "") -> str:
    """
    构建“最终报告撰写”提示词。

    输入：
    - asin: 商品 ASIN
    - analysis_markdown: 数据分析阶段产出的 markdown 统计表
    - product_title: 商品名称（可选）

    输出：
    - prompt: str
    """
    asin = (asin or "").strip()
    product_title = (product_title or "").strip()
    analysis_markdown = (analysis_markdown or "").strip()
    return f"""
你是资深亚马逊跨境电商产品&运营专家，你的任务是基于已完成的评论数据分析结果，生成一份结构化、数据驱动的用户评论洞察报告。
>重要硬性规则：
1. 所有结论**必须严格引用传入的分析数据中的标签、频次、正负评价信息，禁止编造任何不存在的数字、标签；
2. 所有业务洞察，需要带上对应的统计频次作为证据，格式示例：`卡扣不牢(6次)`；
3. 严格区分：正面评价反馈、负面评价反馈；区分核心用户人群、使用场景、硬件质量问题、使用体验、价格感知；
4. 如果数据源样本量有限，报告末尾需要备注样本局限性，不做过度泛化推断。
5. 输出格式：只输出 Markdown；标题包含 ASIN 与产品名称（若提供）

# 报告固定输出结构，严格按照下面模块输出，不要随意增删模块：
> ASIN：{asin}
> 产品名称：{product_title or "未知"}

## 一、数据概览
汇总基础统计信息：总评论数量、正面评价数量、负面评价数量、用户满意度；简单描述整体评分基调。

## 二、高频标签分层分析
按照4个分组整理高频标签，并标注每个标签出现频次：
1）人群&场景标签：目标用户是谁、典型使用场景
2）功能价值标签：用户关心产品功能、核心能力、辅助功能
3）保障价值标签：质量、做工、装配、硬件缺陷相关标签
4）体验价值标签：上手难度、主观喜好、价格感知相关标签

## 三、关键洞察（核心发现总结）
每条洞察做到：【业务结论 + 量化数据证据】
细分4个方向展开：
1. 产品能力两极化表现：哪些功能好评多，哪些功能差评集中；
2. 核心用户画像：什么样的用户是本产品的主要使用者，他们的核心诉求；
3. 主要质量&硬件痛点：差评集中暴露的产品缺陷；
4. 体验与价格感知：用户对上手难度、价格、心理预期的反馈；
5. 高价值辅助功能：哪些附加功能显著影响用户的购买体验。

## 四、用户痛点深度分析
区分3类痛点：
1）硬件结构/做工类痛点（产品本身缺陷）
2）使用体验类痛点（操作、学习门槛、宠物适配等非硬件问题）
3）预期与价格类痛点（性价比感知、心理落差）

## 五、落地行动建议
分为4个板块，每一条建议必须和上面发现的痛点/优势一一对应，拒绝空泛话术：
1. 产品优化建议：硬件结构、做工、功能迭代方向
2. 用户使用指南建议：说明书、详情页使用指引、宠物驯化引导文案
3. 亚马逊市场营销建议：Listing/A+页面/QA可以重点突出的卖点；需要规避、需要提前解释的风险点；面向目标人群的宣传侧重点
4. 价格&产品版本策略：版本规划、价值传递思路

## 六、运营素材提取（附加输出）
1. 【Listing优质卖点词清单】：从好评标签提取，可直接用于标题、五点描述、A+
2. 【风险警示词清单】：差评高频标签，QA、详情页需要提前说明规避客诉

## 七、数据局限性备注
简单说明本报告结论仅基于当前这批评论样本，样本规模会影响结论通用性。

=====传入的数据分析结果=====
{analysis_markdown}
""".strip()


def build_html_report_prompt(asin: str, product_title: str, final_report_markdown: str) -> str:
    """
    构建“可视化HTML报告生成”提示词。
    """
    return f"""
你是擅长结合数据分析和可视化设计的前端工程师。你的任务是将一份 Markdown 格式的电商评论洞察报告，转化为一份结构化、可视化友好的深色科技感 HTML 页面。

## 核心设计要求：
1. 框架与样式库：使用 Tailwind CSS CDN (<script src="https://cdn.tailwindcss.com"></script>) 和 FontAwesome 图标库 (<link rel="stylesheet" href="https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/css/all.min.css">)。
2. 整体主题：深色科技仪表盘风格。背景色 `#0b1220`，卡片背景 `#2a3654`（带半透明毛玻璃效果 `backdrop-filter: blur(10px)`），文字主色 `#e2e8f0`，高亮色 `#60a5fa`。
3. 排版布局：整体居中，最大宽度 `max-w-6xl`。采用卡片式布局（Card），每个主要分析模块占据一个独立的圆角卡片。
4. 组件规范：
   - 数据概览：提炼出核心数字（如总评论数、正面评价、负面评价、满意度），用大字号显著展示。如果有评分分布数据，请用彩色进度条展示。
   - 标签展示：将高频标签转换为圆角胶囊（Tag Pill）样式，并在标签旁带上数字气泡。根据人群、功能、保障、体验四个维度使用不同的颜色（如红、蓝、绿、紫的浅色透明背景）。
   - 图表区：使用特定的占位符作为图片的 `src`：
     - 评分分布图：`src="[RATING_DISTRIBUTION_SVG]"`
     - 高频标签图：`src="[TAG_TOP_SVG]"`
     - 时间趋势图：`src="[MONTHLY_TREND_SVG]"`
     图片容器需要自适应，设置合适的 padding 和背景。
   - 关键洞察与行动建议：去除枯燥的纯文本段落，改用带色彩图标的列表布局，重要字眼（如痛点、改进点）进行颜色高亮，提升可读性。
   - 评论原声：提取优质好评和严重差评的代表性原句，做成对比的引言卡片。
5. 代码输出规范：
   - 必须输出完整的 HTML 代码（包含 `<!DOCTYPE html>`、`<html>`、`<head>`、`<body>`）。
   - 请直接输出 HTML 代码，**不要**在开头和结尾使用 ```html 和 ``` 的 Markdown 代码块包裹，直接输出纯文本形式的代码。

## 商品信息
- ASIN: {asin}
- 产品名称: {product_title}

## Markdown 报告内容
{final_report_markdown}
""".strip()


